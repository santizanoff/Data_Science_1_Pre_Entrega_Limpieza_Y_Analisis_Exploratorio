import pandas as pd
import numpy as np

url = 'https://raw.githubusercontent.com/santizanoff/Dataset_Prueba/refs/heads/main/credit_risk_dataset.csv'
df = pd.read_csv(url)

# Información general del DataFrame (tipos de datos y valores no nulos)
print("--- INFORMACIÓN GENERAL ---")
df.info()

# Resumen estadístico de las variables
print("\n--- RESUMEN ESTADÍSTICO ---")
display(df.describe(include='all'))

# Conteo de valores nulos por columna
print("\n--- VALORES NULOS POR COLUMNA ---")
display(df.isnull().sum())

"""### Proceso de Limpieza Rigurosa del Dataset
Eliminación de duplicados, corrección de outliers obvios e imputación de valores faltantes.
"""

# 1. Eliminar duplicados
print(f"Filas antes de eliminar duplicados: {df.shape[0]}")
df = df.drop_duplicates()
print(f"Filas después de eliminar duplicados: {df.shape[0]}")

# 2. Tratamiento de Outliers extremos evidentes
# Edades mayores a 100 años no son realistas para solicitantes activos de crédito
df = df[df['person_age'] <= 100]

# La experiencia laboral no puede ser mayor que la edad
df = df[df['person_emp_length'] < df['person_age']]

print(f"Filas después de filtrar outliers de edad y empleo: {df.shape[0]}")

# 3. Imputación de valores faltantes utilizando la mediana
emp_length_median = df['person_emp_length'].median()
int_rate_median = df['loan_int_rate'].median()

df['person_emp_length'] = df['person_emp_length'].fillna(emp_length_median)
df['loan_int_rate'] = df['loan_int_rate'].fillna(int_rate_median)

# Verificar el estado final de los valores nulos
print("Valores nulos restantes por columna:")
print(df.isnull().sum())

# Corregir error común: Resetear el índice tras eliminar filas (duplicados y outliers)
df = df.reset_index(drop=True)
print(f"Índice reseteado con éxito. El DataFrame final tiene {df.shape[0]} registros listos para usar.")

"""### Agregaciones de Negocio
Se generan 3 agrupaciones que responden a preguntas críticas de negocio para entender el comportamiento del riesgo crediticio.
"""

# Agrupación 1: Comportamiento del préstamo según la situación de la vivienda del solicitante
agg_home = df.groupby('person_home_ownership').agg(
    cantidad_solicitudes=('loan_status', 'count'),
    tasa_mora_promedio=('loan_status', 'mean'),
    monto_promedio_credito=('loan_amnt', 'mean')
).reset_index()

print("--- Agrupación por Tipo de Propiedad de Vivienda ---")
display(agg_home)

"""**1. Riesgo según el tipo de propiedad de vivienda (person_home_ownership):**

**Inquilinos (RENT):** Tienen una de las tasas de mora más altas con un 31.1%, a pesar de solicitar montos promedio más bajos ($8,926).

**Propietarios con hipoteca (`MORTGAGE`):** Tienen una tasa de mora significativamente menor (**12.5%**), pero son quienes acceden a los montos promedio más altos ($10,652).

**Propietarios absolutos (OWN):** Representan el segmento más seguro, con una tasa de mora de apenas el 6.9%.
"""

# Agrupación 2: Comportamiento del préstamo según el propósito del crédito
agg_intent = df.groupby('loan_intent').agg(
    cantidad_solicitudes=('loan_status', 'count'),
    tasa_mora_promedio=('loan_status', 'mean'),
    monto_promedio_credito=('loan_amnt', 'mean')
).reset_index()

print("\n--- Agrupación por Propósito del Préstamo ---")
display(agg_intent)

"""**2. Riesgo según el propósito del crédito (loan_intent):**

**Consolidación de deudas (DEBTCONSOLIDATION):** Presenta la tasa de mora más alta con un 28.4%.

**Mejoras del hogar (HOMEIMPROVEMENT) y Salud (MEDICAL):** También reflejan un alto nivel de riesgo, con tasas de mora del 25.6% y 26.6% respectivamente.

**Emprendimientos (VENTURE) y Educación (EDUCATION):** Son los destinos de crédito más seguros, con tasas de mora de 14.7% y 17.0% respectivamente.
"""

# Agrupación 3: Comportamiento del préstamo según la calificación crediticia
agg_grade = df.groupby('loan_grade').agg(
    cantidad_solicitudes=('loan_status', 'count'),
    tasa_mora_promedio=('loan_status', 'mean'),
    monto_promedio_credito=('loan_amnt', 'mean')
).reset_index()

print("\n--- Agrupación por Calificación del Préstamo (Grade) ---")
display(agg_grade)

"""**3. Riesgo según la calificación crediticia (loan_grade):**

**Grados A y B:** Se comportan como créditos de bajo riesgo, con tasas de mora de 9.6% y 16.0%.

**Grados D, E, F y G:** Representan un riesgo extremadamente alto. En especial, el Grado G alcanza una tasa de mora del 98.4%, casi garantizando el impago, aunque son pocos los préstamos otorgados en esta categoría.
"""